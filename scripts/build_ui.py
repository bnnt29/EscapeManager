#!/usr/bin/env python3
"""Builds the firmware's embedded UI from src/manager/manager.html and tools/setup/setup.html.

Outputs (all committed, all deterministic):
  src/manager/manager.html.gz   gzip with a fixed header (mtime 0, OS 255), raw deflate level 9
  tools/setup/setup.html.gz     the same for the USB/Web-Serial setup page
  src/manager/ui_data.cpp       both pages as C arrays (EscapeUi, EscapeSetup) + EscapeVersion::UI_HASH

The library embeds the UI as normal C arrays, so a host program needs no
board_build.embed_files setting. The .gz files stay for hosts that still embed
them (unused by the library now).

  python3 scripts/build_ui.py           regenerate when the source changed
  python3 scripts/build_ui.py --check   exit 1 if the committed outputs are stale (CI)

Also usable as a PlatformIO `extra_scripts = pre:scripts/build_ui.py`.
Staleness is decided by CONTENT (the gz must decompress to the current source and
ui_data.cpp must carry its hash), not by comparing compressed bytes, so the result does
not depend on the zlib build.
"""
import gzip
import hashlib
import pathlib
import struct
import sys
import zlib

SRC = GZ = SETUP_SRC = SETUP_GZ = CPP = None


def set_root(root: pathlib.Path) -> None:
    global SRC, GZ, SETUP_SRC, SETUP_GZ, CPP
    SRC = root / "src" / "manager" / "manager.html"
    GZ = root / "src" / "manager" / "manager.html.gz"
    SETUP_SRC = root / "tools" / "setup" / "setup.html"
    SETUP_GZ = root / "tools" / "setup" / "setup.html.gz"
    CPP = root / "src" / "manager" / "ui_data.cpp"


def deterministic_gzip(data: bytes) -> bytes:
    comp = zlib.compressobj(9, zlib.DEFLATED, -15)
    body = comp.compress(data) + comp.flush()
    header = b"\x1f\x8b\x08\x00\x00\x00\x00\x00\x02\xff"  # no name, mtime 0, max compression, OS unknown
    return header + body + struct.pack("<II", zlib.crc32(data) & 0xFFFFFFFF, len(data) & 0xFFFFFFFF)


def ui_hash(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()[:8]


def render_array(name: str, gz: bytes, digest: str = "") -> str:
    lines = ["  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + "," for i in range(0, len(gz), 20)]
    hash_line = ('const char *const hash = "%s";\n' % digest) if digest else ""
    return ("namespace %s {\n%sconst size_t length = %d;\nconst uint8_t data[] = {\n%s\n};\n"
            "} // namespace %s\n" % (name, hash_line, len(gz), "\n".join(lines), name))


def render_cpp(gz: bytes, digest: str, setup_gz: bytes, setup_digest: str) -> str:
    return (
        "// GENERATED by scripts/build_ui.py from manager.html and tools/setup/setup.html - do not edit.\n"
        '#include "UiData.hpp"\n'
        '#include "../protocol/EscapeVersion.hpp"\n\n'
        'const char *const EscapeVersion::UI_HASH = "%s";\n\n'
        % digest
    ) + render_array("EscapeUi", gz) + "\n" + render_array("EscapeSetup", setup_gz, setup_digest)


def page_current(src: pathlib.Path, gz: pathlib.Path, cpp_text: str) -> bool:
    try:
        if not src.exists() or not gz.exists() or gzip.decompress(gz.read_bytes()) != src.read_bytes():
            return False
    except (OSError, EOFError, zlib.error):
        return False
    return ("length = %d;" % len(gz.read_bytes())) in cpp_text


def is_current() -> bool:
    if not (SRC.exists() and GZ.exists() and SETUP_SRC.exists() and SETUP_GZ.exists() and CPP.exists()):
        return False
    text = CPP.read_text()
    return ('UI_HASH = "%s"' % ui_hash(SRC.read_bytes())) in text \
        and ('hash = "%s"' % ui_hash(SETUP_SRC.read_bytes())) in text \
        and page_current(SRC, GZ, text) and page_current(SETUP_SRC, SETUP_GZ, text)


def generate(force: bool = False) -> bool:
    """Returns True if files were (re)written."""
    if not SRC.exists():
        print("[build_ui] source missing: %s" % SRC, file=sys.stderr)
        raise SystemExit(1)
    if not SETUP_SRC.exists():
        print("[build_ui] source missing: %s" % SETUP_SRC, file=sys.stderr)
        raise SystemExit(1)
    if not force and is_current():
        return False
    html = SRC.read_bytes()
    gz = deterministic_gzip(html)
    setup_html = SETUP_SRC.read_bytes()
    setup_gz = deterministic_gzip(setup_html)
    GZ.write_bytes(gz)
    SETUP_GZ.write_bytes(setup_gz)
    CPP.write_text(render_cpp(gz, ui_hash(html), setup_gz, ui_hash(setup_html)))
    for label, src, out in (("manager.html", html, gz), ("setup.html", setup_html, setup_gz)):
        saved = 100 - (len(out) * 100 // max(len(src), 1))
        print("[build_ui] %s: %d -> %d bytes (-%d%%)" % (label, len(src), len(out), saved))
    print("[build_ui] ui_data.cpp: UI hash %s" % ui_hash(html))
    return True


try:  # running inside PlatformIO (extra_scripts): __file__ is not defined there
    Import("env")  # noqa: F821
    set_root(pathlib.Path(env["PROJECT_DIR"]))  # noqa: F821
    generate()
except NameError:
    if __name__ == "__main__":
        set_root(pathlib.Path(__file__).resolve().parent.parent)
        if "--check" in sys.argv:
            ok = is_current()
            print("ui outputs are %s" % ("current" if ok else "STALE - run scripts/build_ui.py"))
            raise SystemExit(0 if ok else 1)
        generate(force="--force" in sys.argv)
