#!/usr/bin/env python3
"""Builds the firmware's embedded manager UI from src/manager/manager.html.

Outputs (both committed, both deterministic):
  src/manager/manager.html.gz   gzip with a fixed header (mtime 0, OS 255), raw deflate level 9
  src/manager/ui_data.cpp       the same bytes as a C array + EscapeVersion::UI_HASH

The library embeds the UI as a normal C array, so a host program needs no
board_build.embed_files setting. The .gz file stays for hosts that still embed it
(unused by the library now).

  python3 scripts/build_ui.py           regenerate when the source changed
  python3 scripts/build_ui.py --check   exit 1 if the committed outputs are stale (CI)

Also usable as a PlatformIO `extra_scripts = pre:scripts/build_ui.py`.
Staleness is decided by CONTENT (the gz must decompress to the current source and
ui_data.cpp must carry its hash), not by comparing compressed bytes, so the result does
not depend on the zlib build.
"""
import gzip
import hashlib
import pathlib
import struct
import sys
import zlib

SRC = GZ = CPP = None


def set_root(root: pathlib.Path) -> None:
    global SRC, GZ, CPP
    SRC = root / "src" / "manager" / "manager.html"
    GZ = root / "src" / "manager" / "manager.html.gz"
    CPP = root / "src" / "manager" / "ui_data.cpp"


def deterministic_gzip(data: bytes) -> bytes:
    comp = zlib.compressobj(9, zlib.DEFLATED, -15)
    body = comp.compress(data) + comp.flush()
    header = b"\x1f\x8b\x08\x00\x00\x00\x00\x00\x02\xff"  # no name, mtime 0, max compression, OS unknown
    return header + body + struct.pack("<II", zlib.crc32(data) & 0xFFFFFFFF, len(data) & 0xFFFFFFFF)


def ui_hash(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()[:8]


def render_cpp(gz: bytes, digest: str) -> str:
    lines = []
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
    return (
        "// GENERATED by scripts/build_ui.py from manager.html - do not edit.\n"
        '#include "UiData.hpp"\n'
        '#include "../protocol/EscapeVersion.hpp"\n\n'
        'const char *const EscapeVersion::UI_HASH = "%s";\n\n'
        "namespace EscapeUi {\n"
        "const size_t length = %d;\n"
        "const uint8_t data[] = {\n%s\n};\n"
        "} // namespace EscapeUi\n" % (digest, len(gz), "\n".join(lines))
    )


def is_current() -> bool:
    if not (SRC.exists() and GZ.exists() and CPP.exists()):
        return False
    html = SRC.read_bytes()
    try:
        if gzip.decompress(GZ.read_bytes()) != html:
            return False
    except (OSError, EOFError, zlib.error):
        return False
    text = CPP.read_text()
    return ('UI_HASH = "%s"' % ui_hash(html)) in text and ("length = %d;" % len(GZ.read_bytes())) in text


def generate(force: bool = False) -> bool:
    """Returns True if files were (re)written."""
    if not SRC.exists():
        print("[build_ui] source missing: %s" % SRC, file=sys.stderr)
        raise SystemExit(1)
    if not force and is_current():
        return False
    html = SRC.read_bytes()
    gz = deterministic_gzip(html)
    GZ.write_bytes(gz)
    CPP.write_text(render_cpp(gz, ui_hash(html)))
    saved = 100 - (len(gz) * 100 // max(len(html), 1))
    print("[build_ui] manager.html: %d -> %d bytes (-%d%%), hash %s" % (len(html), len(gz), saved, ui_hash(html)))
    return True


try:  # running inside PlatformIO (extra_scripts): __file__ is not defined there
    Import("env")  # noqa: F821
    set_root(pathlib.Path(env["PROJECT_DIR"]))  # noqa: F821
    generate()
except NameError:
    if __name__ == "__main__":
        set_root(pathlib.Path(__file__).resolve().parent.parent)
        if "--check" in sys.argv:
            ok = is_current()
            print("ui outputs are %s" % ("current" if ok else "STALE - run scripts/build_ui.py"))
            raise SystemExit(0 if ok else 1)
        generate(force="--force" in sys.argv)
