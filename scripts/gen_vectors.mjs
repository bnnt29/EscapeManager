#!/usr/bin/env node
// Generates the proto-2 test vectors from PROTOCOL.md with an implementation that
// is independent of the C++ and Python code (Node's built-in crypto).
//
//   node scripts/gen_vectors.mjs            -> writes test/fixtures/proto2/vectors.json
//                                              and test/test_core/vectors.hpp
//   node scripts/gen_vectors.mjs --check    -> fails if the committed files are stale
//
// Everything here is deterministic (fixed IVs, fixed times) so the output is stable.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const KDF_SALT = "EscapeManager/2/token";
const KDF_ITER = 2048;
const DEFAULT_TOKEN = "EscapeManager-Private-WLAN-Default-Token";

const b64u = (buf) => Buffer.from(buf).toString("base64url");
const hex = (buf) => Buffer.from(buf).toString("hex");

function hkdf(ikm, info) {
  return Buffer.from(crypto.hkdfSync("sha256", ikm, Buffer.alloc(0), Buffer.from(info), 32));
}

function keysFor(token) {
  const master = crypto.pbkdf2Sync(Buffer.from(token), KDF_SALT, KDF_ITER, 32, "sha256");
  return { master, req: hkdf(master, "EM2 req"), resp: hkdf(master, "EM2 resp"), mac: hkdf(master, "EM2 mac") };
}

function gcmSeal(key, iv, aad, plaintext) {
  const c = crypto.createCipheriv("aes-256-gcm", key, iv);
  c.setAAD(Buffer.from(aad));
  const ct = Buffer.concat([c.update(Buffer.from(plaintext)), c.final()]);
  return Buffer.concat([ct, c.getAuthTag()]);
}

const hmac = (key, msg) => crypto.createHmac("sha256", key).update(msg).digest();

function fnv1a32(text) {
  let h = 0x811c9dc5;
  for (const b of Buffer.from(text)) {
    h ^= b;
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}

const did = "aabbccddeeff";
const out = { description: "proto 2 test vectors, generated by scripts/gen_vectors.mjs", kdf: { salt: KDF_SALT, iter: KDF_ITER }, did, tokens: [] };

for (const token of [DEFAULT_TOKEN, "correct-horse-battery-staple"]) {
  const k = keysFor(token);
  const entry = { token, master: hex(k.master), kReq: hex(k.req), kResp: hex(k.resp), kMac: hex(k.mac) };

  // POST request + response
  const t = 123456;
  const reqIv = Buffer.from("000102030405060708090a0b", "hex");
  const reqPlain = '{"id":0,"action":"open"}';
  const reqAad = `EM2|req|${did}|/action|${t}`;
  const reqCt = gcmSeal(k.req, reqIv, reqAad, reqPlain);
  entry.post = {
    path: "/action", t, iv: b64u(reqIv), plaintext: reqPlain, aad: reqAad,
    envelope: JSON.stringify({ v: 2, t, iv: b64u(reqIv), ct: b64u(reqCt) }),
  };
  const respIv = Buffer.from("0c0d0e0f1011121314151617", "hex");
  const respPlain = '{"ok":true}';
  const respAad = `EM2|resp|${did}|/action|${b64u(reqIv)}|200`;
  entry.postResponse = {
    status: 200, iv: b64u(respIv), plaintext: respPlain, aad: respAad,
    envelope: JSON.stringify({ v: 2, iv: b64u(respIv), ct: b64u(gcmSeal(k.resp, respIv, respAad, respPlain)) }),
  };

  // Authenticated GET frame
  const doc = '{"proto":2,"did":"aabbccddeeff","seq":17,"components":[]}';
  const nonce = "0123456789abcdefGHIJ_-";
  const getMac = b64u(hmac(k.mac, `EM2|get|${did}|/status.json|${nonce}|200|${doc}`));
  entry.get = { path: "/status.json", nonce, status: 200, doc, frame: `{"doc":${doc},"mac":"${getMac}"}` };

  // UDP announcement
  const udpDoc = '{"v":2,"did":"aabbccddeeff","ip":"192.168.1.20","port":80,"boot":5,"ctr":123,"seq":17,"pmin":2,"uih":"1a2b3c4d","sk":[["a1b2c3d4",3,"9f8e7d6c"]]}';
  entry.udp = { doc: udpDoc, frame: `{"doc":${udpDoc},"mac":"${b64u(hmac(k.mac, "EM2|udp|" + udpDoc))}"}` };

  out.tokens.push(entry);
}

// RFC 5869 test case 1 (HKDF-SHA256) to pin the primitive itself.
out.hkdfRfc5869 = {
  ikm: "0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b",
  salt: "000102030405060708090a0b0c",
  info: "f0f1f2f3f4f5f6f7f8f9",
  length: 42,
  okm: hex(Buffer.from(crypto.hkdfSync("sha256", Buffer.from("0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b", "hex"),
    Buffer.from("000102030405060708090a0b0c", "hex"), Buffer.from("f0f1f2f3f4f5f6f7f8f9", "hex"), 42))),
};

out.fnv1a32 = ["", "a", "Raum-A", "Escape Room 1", "Käfig/Ü"].map((s) => ({ text: s, hash: fnv1a32(s) }));
out.b64u = [
  { hex: "", text: "" }, { hex: "00", text: "AA" }, { hex: "0001", text: "AAE" }, { hex: "000102", text: "AAEC" },
  { hex: "fffefd", text: "__79" }, { hex: "fbff", text: "-_8" },
].map((v) => ({ ...v, text: b64u(Buffer.from(v.hex, "hex")) }));
out.b64uInvalid = ["A", "AAE=", "AB", "A+/A", "AA AA", "AAF"]; // length%4==1, padding, non-canonical tail, std alphabet, space, non-zero tail bits

const json = JSON.stringify(out, null, 2) + "\n";

// ---- C++ header -------------------------------------------------------------
const q = (s) => JSON.stringify(s); // JSON string literals are valid C++ string literals for ASCII/UTF-8 text
let h = "// GENERATED by scripts/gen_vectors.mjs - do not edit.\n#pragma once\nnamespace Vectors {\n";
h += `constexpr const char *kDid = ${q(did)};\n`;
h += `constexpr unsigned kKdfIter = ${KDF_ITER};\nconstexpr const char *kKdfSalt = ${q(KDF_SALT)};\n`;
out.tokens.forEach((e, i) => {
  h += `namespace T${i} {\n`;
  for (const [k, v] of [["token", e.token], ["master", e.master], ["kReq", e.kReq], ["kResp", e.kResp], ["kMac", e.kMac],
    ["postPath", e.post.path], ["postIv", e.post.iv], ["postPlain", e.post.plaintext], ["postEnvelope", e.post.envelope],
    ["respIv", e.postResponse.iv], ["respPlain", e.postResponse.plaintext], ["respEnvelope", e.postResponse.envelope],
    ["getPath", e.get.path], ["getNonce", e.get.nonce], ["getDoc", e.get.doc], ["getFrame", e.get.frame],
    ["udpDoc", e.udp.doc], ["udpFrame", e.udp.frame]]) {
    h += `constexpr const char *${k} = ${q(v)};\n`;
  }
  h += `constexpr unsigned postT = ${e.post.t};\n}\n`;
});
h += `constexpr const char *kHkdfIkm = ${q(out.hkdfRfc5869.ikm)};\nconstexpr const char *kHkdfSalt = ${q(out.hkdfRfc5869.salt)};\n`;
h += `constexpr const char *kHkdfInfo = ${q(out.hkdfRfc5869.info)};\nconstexpr const char *kHkdfOkm = ${q(out.hkdfRfc5869.okm)};\n`;
h += "struct Fnv { const char *text; const char *hash; };\nconstexpr Fnv kFnv[] = {\n";
for (const f of out.fnv1a32) h += `  {${q(f.text)}, ${q(f.hash)}},\n`;
h += "};\nstruct B64 { const char *hex; const char *text; };\nconstexpr B64 kB64[] = {\n";
for (const f of out.b64u) h += `  {${q(f.hex)}, ${q(f.text)}},\n`;
h += "};\nconstexpr const char *kB64Invalid[] = {" + out.b64uInvalid.map(q).join(", ") + "};\n} // namespace Vectors\n";

const targets = [
  [path.join(root, "test/fixtures/proto2/vectors.json"), json],
  [path.join(root, "test/test_core/vectors.hpp"), h],
];
if (process.argv.includes("--check")) {
  let bad = false;
  for (const [file, content] of targets) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) { console.error("stale: " + file); bad = true; }
  }
  process.exit(bad ? 1 : 0);
}
for (const [file, content] of targets) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log("wrote " + path.relative(root, file));
}
